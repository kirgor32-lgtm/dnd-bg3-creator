for c in d["classes"]:
  # перевод навыков
  c["skillChoices"]["options"] = [SKILL_EN_RU.get(s, s) for s in c["skillChoices"]["options"]]
  # пересборка снаряжения в полные комплекты
  if c["id"] in EQUIPMENT:
    c["startingEquipment"] = build_packages(c["id"])

