def build_packages(cls_id):
  spec = EQUIPMENT[cls_id]
  groups = spec["groups"]
  fixed = spec["fixed"]
  n = max((len(g) for g in groups), default=1)
  n = min(n, 3)
  letters = "ABC"
  packages = []
  for i in range(n):
    items = []
    for g in groups:
      items.append(g[i] if i < len(g) else g[0])
    items += fixed
    packages.append({"choice": letters[i], "items": items})
  return packages

