# Проверка на дубли: одинаковый предмет дважды в одном комплекте,
# и слово-пересечение с содержимым набора (pack), который может уже включать похожий предмет.
print("\n--- проверка дублей ---")
problems = 0
for classId, builds in EQUIPMENT_BUILDS.items():
  for b in builds:
    items = b["items"]
    if len(items) != len(set(items)):
      problems += 1
      print(f"ДУБЛЬ ПРЕДМЕТА: {classId} {b['choice']} ({b['role']}) -> {items}")
    pack_items = [i for i in items if "Набор" in i]
    other_items = [i for i in items if "Набор" not in i]
    for pack in pack_items:
      pack_desc = ITEM_INFO.get(pack, "").lower()
      for it in other_items:
        key = it.lower().replace("два ","").replace("ручной ","").rstrip("ов").rstrip("а")
        if len(key) > 3 and key in pack_desc:
          problems += 1
          print(f"ВОЗМОЖНОЕ ПЕРЕСЕЧЕНИЕ С НАБОРОМ: {classId} {b['choice']} -> '{it}' похоже уже упомянут в '{pack}' ({pack_desc})")
print("проблем найдено:" , problems)
